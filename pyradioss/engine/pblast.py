def compute_segment_geometry(nodes_coords: np.ndarray) -> Tuple[np.ndarray, np.ndarray, float]:
    """Compute centroid, normal vector (N = 2 * Area * n), and surface area of 3N/4N segment.

    Matches pblast_1.F lines 228-257:
    - For 3 nodes:
      centroid = (x1 + x2 + x3) / 3
      N = (x3 - x1) x (x3 - x2)
      area = 0.5 * ||N||
    - For 4 nodes:
      centroid = (x1 + x2 + x3 + x4) / 4
      N = (x3 - x1) x (x4 - x2)
      area = 0.5 * ||N||
    """
    coords = np.asarray(nodes_coords, dtype=float)
    npt = len(coords)
    if npt == 3 or (npt == 4 and np.allclose(coords[2], coords[3])):
        centroid = (coords[0] + coords[1] + coords[2]) / 3.0
        v1 = coords[2] - coords[0]
        v2 = coords[2] - coords[1]
        normal_2s = np.cross(v1, v2)
    else:
        centroid = np.mean(coords[:4], axis=0)
        v1 = coords[2] - coords[0]
        v2 = coords[3] - coords[1]
        normal_2s = np.cross(v1, v2)

    norm_2s = float(np.linalg.norm(normal_2s))
    area = 0.5 * norm_2s
    return centroid, normal_2s, area


def compute_effective_pressure(
    cos_theta: float,
    p_inci: float,
    p_refl: float,
    t: float,
    t_a: float,
    dt_0: float,
    decay_inci: float = 1.0,
    decay_refl: float = 1.0,
    pmin: float = 0.0,
) -> float:
    """Compute instantaneous blast overpressure on a surface segment.

    Matches pblast_1.F lines 370-391:
    - If cos(theta) <= 0: alpha_refl = 0, alpha_inci = 1
    - If cos(theta) > 0:  alpha_refl = cos^2(theta), alpha_inci = 1 + cos(theta) - 2 * cos^2(theta)
    - W_inci = P_inci * (1 - tau) * exp(-decay_inci * tau) for tau = (t - t_a) / dt_0 in [0, 1]
    - W_refl = P_refl * (1 - tau) * exp(-decay_refl * tau) for tau = (t - t_a) / dt_0 in [0, 1]
    - P = max(alpha_refl * W_refl + alpha_inci * W_inci, pmin)
    """
    if cos_theta <= 0.0:
        alpha_refl = 0.0
        alpha_inci = 1.0
    else:
        alpha_refl = cos_theta * cos_theta
        alpha_inci = 1.0 + cos_theta - 2.0 * alpha_refl

    if t >= t_a and dt_0 > 0.0:
        tau = (t - t_a) / dt_0
        if tau <= 1.0:
            wave_inci = p_inci * (1.0 - tau) * math.exp(-decay_inci * tau)
            wave_refl = p_refl * (1.0 - tau) * math.exp(-decay_refl * tau)
        else:
            wave_inci = 0.0
            wave_refl = 0.0
    else:
        wave_inci = 0.0
        wave_refl = 0.0

    p = alpha_refl * wave_refl + alpha_inci * wave_inci
    return max(p, pmin)


def compute_segment_blast_pressure(
    load_params: PblastParams,
    seg_nodes_coords: np.ndarray,
    t: float,
    dt: float = 0.0,
    unit_factors: Tuple[float, float, float] = (1.0, 1.0, 1.0),
) -> Tuple[float, float, float, float]:
    """Compute pressure, cos(theta), t_a, and dt_0 for a single segment at time t.

    Returns:
        (pressure, cos_theta, t_a, dt_0)
    """
    fac_m, fac_l, fac_t = unit_factors
    fac_m_bb = fac_m * 1.0e3
    fac_l_bb = fac_l * 1.0e2
    fac_t_bb = fac_t * 1.0e6
    fac_p_bb = fac_m_bb / (fac_l_bb * fac_t_bb * fac_t_bb)
    fac_i_bb = fac_m_bb / (fac_l_bb * fac_t_bb)

    centroid, normal_2s, area = compute_segment_geometry(seg_nodes_coords)
    norm_2s = float(np.linalg.norm(normal_2s))

    dx = (load_params.xdet - centroid[0]) * fac_l_bb
    dy = (load_params.ydet - centroid[1]) * fac_l_bb
    dz = (load_params.zdet - centroid[2]) * fac_l_bb
    dnorm = math.sqrt(dx * dx + dy * dy + dz * dz)

    if norm_2s > 1e-20 and dnorm > 1e-20:
        cos_theta = (dx * normal_2s[0] + dy * normal_2s[1] + dz * normal_2s[2]) / (norm_2s * dnorm)
    else:
        cos_theta = 0.0

    wtnt_g = max(1e-12, load_params.wtnt * fac_m_bb)
    w13 = wtnt_g ** (1.0 / 3.0)
    z_scaled = max(0.5, min(400.0, dnorm / w13))

    compute_decay = (load_params.imodel == 2)
    if load_params.exp_data == BurstType.SURFACE_BURST:
        fp = pblast_parameters_surface_burst(
            z_scaled, w13, load_params.tdet,
            fac_p_bb, fac_i_bb, fac_t_bb,
            compute_decay=compute_decay,
        )
    else:
        fp = pblast_parameters_free_air(
            z_scaled, w13, load_params.tdet,
            fac_p_bb, fac_i_bb, fac_t_bb,
            compute_decay=compute_decay,
        )

    press = compute_effective_pressure(
        cos_theta, fp.p_inci, fp.p_refl, t, fp.t_a, fp.dt_0,
        decay_inci=fp.decay_inci, decay_refl=fp.decay_refl, pmin=load_params.pmin,
    )

    return press, cos_theta, fp.t_a, fp.dt_0


class PblastEngine:
    """Engine managing blast wave loading across surface segments."""

    def __init__(
        self,
        model: Any = None,
        loads: Optional[Sequence[Union[PblastParams, Any]]] = None,
        node_coords: Optional[np.ndarray] = None,
        segments: Optional[Sequence[Sequence[int]]] = None,
    ):
        self.model = model
        self.cumulative_work: float = 0.0
        self.time: float = 0.0

        # Resolve unit conversion factors
        # fac_mass, fac_length, fac_time to SI
        fac_m = 1.0
        fac_l = 1.0
        fac_t = 1.0
        if model is not None and getattr(model, "unit_work", None) is not None:
            uw = model.unit_work
            if len(uw) >= 3:
                fac_m, fac_l, fac_t = float(uw[0]), float(uw[1]), float(uw[2])

        self.fac_m_bb = fac_m * 1.0e3   # kg -> g
        self.fac_l_bb = fac_l * 1.0e2   # m -> cm
        self.fac_t_bb = fac_t * 1.0e6   # s -> mus
        self.fac_p_bb = self.fac_m_bb / (self.fac_l_bb * self.fac_t_bb * self.fac_t_bb)
        self.fac_i_bb = self.fac_m_bb / (self.fac_l_bb * self.fac_t_bb)

        # Collect loads
        self.loads: List[PblastParams] = []
        if loads is not None:
            for ld in loads:
                if isinstance(ld, PblastParams):
                    self.loads.append(ld)
                else:
                    self.loads.append(self._convert_load(ld))
        elif model is not None:
            for ld in getattr(model, "pblast_loads", {}).values():
                self.loads.append(self._convert_load(ld))

        # Node coordinates
        if node_coords is not None:
            self.coords = np.asarray(node_coords, dtype=float)
        elif model is not None and hasattr(model, "x0"):
            self.coords = np.asarray(model.x0, dtype=float)
        else:
            self.coords = np.zeros((0, 3), dtype=float)

        # Per-load segment wave cache
        self.segment_cache: Dict[int, List[dict]] = {}
        self._init_segment_cache(segments)

    def _convert_load(self, ent: Any) -> PblastParams:
        p = PblastParams(
            id=getattr(ent, "id", 1),
            title=getattr(ent, "title", ""),
            surf_id=getattr(ent, "surf_id", 0),
            exp_data=getattr(ent, "exp_data", getattr(ent, "iabac", 1)),
            i_tshift=getattr(ent, "i_tshift", getattr(ent, "ita_shift", 1)),
            ndt=getattr(ent, "ndt", 0),
            iz=getattr(ent, "iz", getattr(ent, "iz_update", 2)),
            imodel=getattr(ent, "imodel", 0),
            node_id=getattr(ent, "node_id", 0),
            xdet=float(getattr(ent, "xdet", 0.0)),
            ydet=float(getattr(ent, "ydet", 0.0)),
            zdet=float(getattr(ent, "zdet", 0.0)),
            tdet=float(getattr(ent, "tdet", 0.0)),
            wtnt=float(getattr(ent, "wtnt", 0.0)),
            pmin=float(getattr(ent, "pmin", 0.0)),
            tstop=float(getattr(ent, "tstop", 1.0e30)),
            surf_ground_id=getattr(ent, "surf_ground_id", 0),
            ishape=getattr(ent, "ishape", 0),
        )
        return p

    def _resolve_segments(self, load: PblastParams, default_segments: Optional[Sequence[Sequence[int]]] = None) -> List[List[int]]:
        if load.segments is not None:
            return [list(s) for s in load.segments]
        if default_segments is not None:
            return [list(s) for s in default_segments]
        if self.model is not None and hasattr(self.model, "surfaces") and load.surf_id in self.model.surfaces:
            surf = self.model.surfaces[load.surf_id]
            if hasattr(surf, "segments") and surf.segments is not None:
                return [list(s) for s in surf.segments]
            if hasattr(surf, "seg_nodes") and surf.seg_nodes:
                if hasattr(self.model, "_id2idx"):
                    return [[self.model._id2idx[nid] for nid in s if nid in self.model._id2idx] for s in surf.seg_nodes]
                return [list(s) for s in surf.seg_nodes]
        return []

    def _init_segment_cache(self, default_segments: Optional[Sequence[Sequence[int]]] = None):
        for ld in self.loads:
            segs = self._resolve_segments(ld, default_segments)
            cache_list = []
            for s in segs:
                cache_list.append({
                    "nodes": s,
                    "cos_theta": 0.0,
                    "p_inci": 0.0,
                    "p_refl": 0.0,
                    "t_a": 0.0,
                    "dt_0": 0.0,
                    "decay_inci": 1.0,
                    "decay_refl": 1.0,
                    "initialized": False,
                })
            self.segment_cache[ld.id] = cache_list

    def evaluate_step(
        self,
        t: float,
        dt: float,
        coords: Optional[np.ndarray] = None,
        v: Optional[np.ndarray] = None,
    ) -> PblastStepResult:
        """Evaluate blast loading at time t for time increment dt."""
        if coords is not None:
            x = np.asarray(coords, dtype=float)
        else:
            x = self.coords

        numnod = len(x)
        nodal_forces = np.zeros((numnod, 3), dtype=float)
        all_pressures: List[float] = []
        all_forces: List[np.ndarray] = []
        work_step = 0.0

        for ld in self.loads:
            if t > ld.tstop:
                continue

            # Detonation center coordinates
            xdet, ydet, zdet = ld.xdet, ld.ydet, ld.zdet
            if ld.node_id > 0:
                nidx = -1
                if self.model is not None and hasattr(self.model, "_id2idx") and ld.node_id in self.model._id2idx:
                    nidx = self.model._id2idx[ld.node_id]
                elif 0 <= ld.node_id < numnod:
                    nidx = ld.node_id
                if 0 <= nidx < numnod:
                    xdet, ydet, zdet = x[nidx, 0], x[nidx, 1], x[nidx, 2]

            # Scaled explosive mass
            # W13 = (WTNT * FAC_M_bb)**(1/3)
            wtnt_g = max(1e-12, ld.wtnt * self.fac_m_bb)
            w13 = wtnt_g ** (1.0 / 3.0)

            compute_decay = (ld.imodel == 2)
            c_list = self.segment_cache.get(ld.id, [])

            for item in c_list:
                node_indices = item["nodes"]
                npt = len(node_indices)
                if npt < 3:
                    continue

                seg_coords = x[node_indices]
                centroid, normal_2s, area = compute_segment_geometry(seg_coords)
                norm_2s = float(np.linalg.norm(normal_2s))

                # Update wave parameters if iz == 2 or not initialized
                if ld.iz == 2 or not item["initialized"]:
                    # Vector from centroid to detonation point
                    dx = (xdet - centroid[0]) * self.fac_l_bb
                    dy = (ydet - centroid[1]) * self.fac_l_bb
                    dz = (zdet - centroid[2]) * self.fac_l_bb
                    dnorm = math.sqrt(dx * dx + dy * dy + dz * dz)

                    # Cosine of angle between outward normal and incident ray
                    if norm_2s > 1e-20 and dnorm > 1e-20:
                        cos_theta = (dx * normal_2s[0] + dy * normal_2s[1] + dz * normal_2s[2]) / (norm_2s * dnorm)
                    else:
                        cos_theta = 0.0

                    # Scaled distance Z [cm / g^(1/3)]
                    z_scaled = max(0.5, min(400.0, dnorm / w13))

                    if ld.exp_data == BurstType.SURFACE_BURST:
                        fp = pblast_parameters_surface_burst(
                            z_scaled, w13, ld.tdet,
                            self.fac_p_bb, self.fac_i_bb, self.fac_t_bb,
                            compute_decay=compute_decay,
                        )
                    else:
                        fp = pblast_parameters_free_air(
                            z_scaled, w13, ld.tdet,
                            self.fac_p_bb, self.fac_i_bb, self.fac_t_bb,
                            compute_decay=compute_decay,
                        )

                    item["cos_theta"] = cos_theta
                    item["p_inci"] = fp.p_inci
                    item["p_refl"] = fp.p_refl
                    item["t_a"] = fp.t_a
                    item["dt_0"] = fp.dt_0
                    item["decay_inci"] = fp.decay_inci
                    item["decay_refl"] = fp.decay_refl
                    item["initialized"] = True

                # Compute pressure at current time
                cos_theta = item["cos_theta"]
                p_inci = item["p_inci"]
                p_refl = item["p_refl"]
                t_a = item["t_a"]
                dt_0 = item["dt_0"]
                d_inci = item["decay_inci"]
                d_refl = item["decay_refl"]

                press = compute_effective_pressure(
                    cos_theta, p_inci, p_refl, t, t_a, dt_0,
                    decay_inci=d_inci, decay_refl=d_refl, pmin=ld.pmin,
                )

                # Segment force: F = -P * Area * n = -P * 0.5 * normal_2s
                # Distributed to NPT nodes: F_node = -P * (0.5 * normal_2s) / NPT
                f_seg = -press * (0.5 * normal_2s)
                f_node = f_seg / float(npt)

                all_pressures.append(press)
                all_forces.append(f_seg)

                # Distribute to nodes
                for n_idx in node_indices:
                    if 0 <= n_idx < numnod:
                        nodal_forces[n_idx] += f_node

                # External work increment: Delta W = Delta t * sum_k dot(F_node, v_k)
                if v is not None and dt > 0.0:
                    v_seg = v[node_indices]
                    v_sum = np.sum(v_seg, axis=0)
                    work_step += dt * float(np.dot(f_node, v_sum))

        self.cumulative_work += work_step
        self.time = t + dt

        return PblastStepResult(
            time=t,
            dt=dt,
            segment_pressures=np.array(all_pressures, dtype=float),
            segment_forces=np.array(all_forces, dtype=float) if all_forces else np.zeros((0, 3)),
            nodal_forces=nodal_forces,
            work_step=work_step,
            cumulative_work=self.cumulative_work,
        )


def apply_pblast_loads(
    model: Any,
    t: float,
    dt: float,
    fext: Optional[np.ndarray] = None,
    v: Optional[np.ndarray] = None,
) -> Tuple[np.ndarray, float]:
    """Top-level dispatcher applying /LOAD/PBLAST external forces to model."""
    if not hasattr(model, "_pblast_engine") or model._pblast_engine is None:
        model._pblast_engine = PblastEngine(model=model)

    res = model._pblast_engine.evaluate_step(t, dt, coords=getattr(model, "x", None), v=v)

    if fext is not None:
        fext += res.nodal_forces
    else:
        fext = res.nodal_forces

    return fext, res.work_step
