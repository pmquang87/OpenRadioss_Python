_CST_255_DIV_LN_Z1_ON_ZN = -38.147316611455952998
_LOG10_E = 2.30258509299405000000


def interpolate_log_log(z: float, z_table: Sequence[float], val_table: Sequence[float]) -> float:
    """Log-log interpolation matching Fortran pblast_mod.F90 lines 3380-3460."""
    if z <= 0.5:
        return float(val_table[0])
    elif z >= 400.0:
        return float(val_table[255])
    else:
        phi_db = math.log(0.5 / z) * _CST_255_DIV_LN_Z1_ON_ZN
        phi_i = int(phi_db)
        if phi_i < 0:
            phi_i = 0
        elif phi_i >= 255:
            phi_i = 254
        b1 = z_table[phi_i]
        b2 = z_table[phi_i + 1]
        lam = (z - b1) / (b2 - b1)
        v1 = val_table[phi_i]
        v2 = val_table[phi_i + 1]
        logres = math.log10(v1) + lam * math.log10(v2 / v1)
        return math.exp(logres * _LOG10_E)


def solve_friedlander_decay(p_peak: float, dt0: float, impulse: float,
                            max_iter: int = 20, tol: float = 1e-6) -> float:
    """Newton-Raphson solver for Friedlander decay parameter matching pblast_mod.F90."""
    k = p_peak * dt0
    if k <= 0.0 or impulse <= 0.0:
        return 1.0
    zeta = 1.0
    funct = 0.5 * k - impulse
    for _ in range(max_iter):
        if abs(zeta) < 1e-6:
            diff = k * (-1.0 / 6.0 + 1.0 / 12.0 * zeta)
            zeta = zeta - funct / diff
            funct = 0.5 * k - (1.0 / 6.0) * k * zeta - impulse
        else:
            exp_zeta = math.exp(-zeta)
            tmp2 = k * exp_zeta / (zeta * zeta)
            diff = zeta * tmp2 * math.exp(zeta) - (funct + impulse) * (1.0 + 2.0 / zeta)
            zeta = zeta - funct / diff
            exp_zeta = math.exp(-zeta)
            tmp2 = k * exp_zeta / (zeta * zeta)
            tmp3 = math.exp(zeta) * (zeta - 1.0) + 1.0
            funct = tmp2 * tmp3 - impulse
        if abs(funct) <= tol:
            break
    return max(0.0, zeta)


def pblast_parameters_free_air(
    z: float,
    w13: float,
    tdet: float = 0.0,
    fac_p_bb: float = 1.0,
    fac_i_bb: float = 1.0,
    fac_t_bb: float = 1.0,
    compute_decay: bool = False,
) -> FriedlanderParams:
    """Evaluate blast wave characteristic parameters for Free Air burst (spherical charge)."""
    p_inci = interpolate_log_log(z, _RW3, _PSO)
    i_inci = interpolate_log_log(z, _RW3, _ISO)
    p_refl = interpolate_log_log(z, _RW3, _PR)
    i_refl = interpolate_log_log(z, _RW3, _IREFL)
    dt_0 = interpolate_log_log(z, _RW3, _T0)
    t_a = interpolate_log_log(z, _RW3, _TA)

    i_inci *= w13
    i_refl *= w13
    if dt_0 < 1e19:
        dt_0 *= w13
    if t_a < 1e19:
        t_a *= w13

    if not compute_decay:
        decay_inci = 1.0
        decay_refl = 1.0
    else:
        decay_inci = solve_friedlander_decay(p_inci, dt_0, i_inci)
        decay_refl = solve_friedlander_decay(p_refl, dt_0, i_refl)

    p_inci /= fac_p_bb
    i_inci /= fac_i_bb
    p_refl /= fac_p_bb
    i_refl /= fac_i_bb
    if dt_0 < 1e19:
        dt_0 /= fac_t_bb
    if t_a < 1e19:
        t_a = t_a / fac_t_bb + tdet

    return FriedlanderParams(
        p_inci=p_inci,
        p_refl=p_refl,
        i_inci=i_inci,
        i_refl=i_refl,
        t_a=t_a,
        dt_0=dt_0,
        decay_inci=decay_inci,
        decay_refl=decay_refl,
    )


