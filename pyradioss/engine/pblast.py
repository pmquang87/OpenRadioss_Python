"""Blast Pressure Wave Loading (/LOAD/PBLAST, /PBLAST).

Upstream OpenRadioss Fortran References:
- engine/source/loads/pblast/pblast.F (main pblast dispatcher and parallel loop)
- engine/source/loads/pblast/pblast_1.F (Free Air Burst, spherical charge)
- engine/source/loads/pblast/pblast_2.F (Surface Burst, ground reflection)
- engine/source/loads/pblast/pblast_3.F (Air Burst, Mach stem reflection)
- common_source/modules/loads/pblast_mod.F90 (UFC 3-340-02 empirical tables and Newton decay solver)
- starter/source/loads/pblast/hm_read_pblast.F (card parser)

Physics formulation:
1. Hopkinson-Cranz Blast Wave Scaling:
   - Stand-off distance: R = ||x_seg - x_det||
   - Charge mass: W (TNT equivalent mass in working units)
   - Scaled distance: Z = R / W^(1/3) [cm / g^(1/3) in UFC unit system]
   - Characteristic parameters from UFC 3-340-02 (256-point log-log tables):
     * P_so: Peak incident overpressure
     * P_r:  Peak reflected overpressure
     * I_so: Positive incident impulse
     * I_r:  Positive reflected impulse
     * t_a:  Wave arrival time at target
     * t_0:  Positive phase duration
2. Modified Friedlander Wave Formulation:
   - For t* >= t_a where t* = t + t_shift:
     W_inci(t*) = P_so * (1 - (t* - t_a)/t_0) * exp(-alpha_inci * (t* - t_a)/t_0)
     W_refl(t*) = P_r  * (1 - (t* - t_a)/t_0) * exp(-alpha_refl * (t* - t_a)/t_0)
   - For t* < t_a:
     W_inci = 0, W_refl = 0
3. Superposition and Incident Angle Dependence:
   - Centroid x_c and normal N = 2 * S * n (||N|| = 2 * Area)
   - Incident angle cos(theta) = dot(N, x_det - x_c) / (||N|| * R)
   - If cos(theta) <= 0 (shadowed face facing away):
       alpha_refl = 0
       alpha_inci = 1
   - If cos(theta) > 0 (illuminated face facing explosion):
       alpha_refl = cos^2(theta)
       alpha_inci = 1 + cos(theta) - 2 * cos^2(theta)
   - Effective pressure:
       P(t, theta) = max(alpha_refl * W_refl + alpha_inci * W_inci, P_min)
4. Segment Nodal Force Distribution and External Work:
   - Nodal force vector on each node k = 1..NPT of segment:
       F_k = -P * (Area / NPT) * n = -P * (0.5 * N) / NPT
   - External work increment:
       Delta W_ext = Delta t * sum_{k=1}^{NPT} dot(F_k, v_k)
"""

