class BurstType(IntEnum):
    """Burst type / experiment abac ID (UFC 3-340-02)."""
    FREE_AIR = 1       # Spherical charge in free air (pblast_1.F)
    SURFACE_BURST = 2  # Hemispherical charge on ground (pblast_2.F)
    AIR_BURST = 3      # Spherical charge elevated above ground (pblast_3.F)


@dataclass
class FriedlanderParams:
    """Blast wave characteristic parameters from UFC 3-340-02 tables."""
    p_inci: float = 0.0      # Peak incident overpressure
    p_refl: float = 0.0      # Peak reflected overpressure
    i_inci: float = 0.0      # Incident positive impulse
    i_refl: float = 0.0      # Reflected positive impulse
    t_a: float = 0.0         # Wave arrival time
    dt_0: float = 0.0        # Positive phase duration
    decay_inci: float = 1.0  # Modified Friedlander decay parameter for incident wave
    decay_refl: float = 1.0  # Modified Friedlander decay parameter for reflected wave


@dataclass
class PblastParams:
    """Parameters defining a /LOAD/PBLAST air/surface blast load."""
    id: int = 1
    title: str = ""
    surf_id: int = 0
    exp_data: int = 1       # 1=Free Air, 2=Surface Burst, 3=Air Burst
    i_tshift: int = 1       # Time shift mode
    ndt: int = 0            # Number of substeps for arrival time
    iz: int = 2             # 1 = fixed from starter, 2 = dynamic / update
    imodel: int = 0         # 0/1 = standard Friedlander (decay=1), 2 = Newton solver for decay
    node_id: int = 0        # Detonation node ID
    xdet: float = 0.0       # Detonation point X
    ydet: float = 0.0       # Detonation point Y
    zdet: float = 0.0       # Detonation point Z
    tdet: float = 0.0       # Detonation time
    wtnt: float = 0.0       # Equivalent TNT explosive mass
    pmin: float = 0.0       # Minimum pressure cutoff
    tstop: float = 1.0e30   # Blast termination time
    surf_ground_id: int = 0 # Ground reflection surface ID
    ishape: int = 0         # Charge shape (0/1=spherical, 2=hemispherical, 3=cylindrical)
    ground_normal: Sequence[float] = (0.0, 0.0, 1.0)
    ground_height: float = 0.0
    segments: Optional[Sequence[Sequence[int]]] = None


@dataclass
class PblastStepResult:
    """Output of one time step evaluation of blast loading."""
    time: float
    dt: float
    segment_pressures: np.ndarray   # (nseg,) pressure at each segment
    segment_forces: np.ndarray      # (nseg, 3) resultant force on each segment
    nodal_forces: np.ndarray        # (numnod, 3) force vector on each model node
    work_step: float                # Delta W_ext external work done during this step
    cumulative_work: float          # Cumulative external work


